/* ************************************************************************** */

export type TodoStatus = 'waiting' | 'in progress' | 'done';

/* ************************************************************************** */
/*                                Interfaces                                  */
/* ************************************************************************** */

export interface Todo {
  id: number;
  name: string;
  content: string;
  status: TodoStatus;
  createdAt?: Date;
  updatedAt?: Date;
}
